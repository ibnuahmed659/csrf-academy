/**
 * The structural (non-translatable) half of a scenario. All learner-facing
 * text is pulled from `LAB_TEXT` in `src/content/labs.ts` so it can be
 * translated in one place.
 */
type ScenarioShell = {
  id: string
  stage: Stage
  category: string
  mode: 'exploit' | 'assess'
  victimName: string
  victimSite: string
  actionPath: string
  actionParams: Record<string, string>
  defense: Defense
  secure: Defense
  sessionToken?: string
  leakedToken?: boolean
}

function make(s: ScenarioShell): LabScenario {
  const t = LAB_TEXT[s.id]
  if (!t) {
    throw new Error(
      `Missing lab text for "${s.id}". Add it to LAB_TEXT in src/content/labs.ts`,
    )
  }
  return {
    id: s.id,
    title: t.title,
    stage: s.stage,
    category: s.category,
    mode: s.mode,
    summary: t.summary,
    takeaway: t.takeaway,
    victim: {
      name: s.victimName,
      site: s.victimSite,
      disclosure: t.victimDisclosure,
    },
    action: {
      label: t.actionLabel,
      path: s.actionPath,
      params: s.actionParams,
      before: t.actionBefore,
      after: t.actionAfter,
    },
    defense: s.defense,
    secure: s.secure,
    sessionToken: s.sessionToken,
    leakedToken: s.leakedToken,
    objectives: t.objectives,
    hints: t.hints,
    walkthrough: t.walkthrough,
  }
}

